<?php

namespace App\Services;

use App\Models\Project;
use App\Models\SiteSection;
use App\Services\Ai\AiClientFactory;
use App\Services\Ai\AiUnavailableException;

class SiteGenerator
{
    public function __construct(private FallbackSiteBuilder $fallback)
    {
    }

    /**
     * Generate (or regenerate) all sections. Returns ['path' => 'ai'|'fallback', 'note' => string].
     * The AI output passes a fact guard: any phone/email appearing in the copy
     * that is not a confirmed fact rejects the whole AI output to the fallback.
     */
    public function generate(Project $project): array
    {
        $facts = $project->confirmedFacts();
        try {
            $sections = AiClientFactory::make()->generateSections($facts);
            $this->guard($sections, $facts);
            $path = 'ai';
            $note = 'Website generated by AI from confirmed facts only.';
        } catch (AiUnavailableException $e) {
            $sections = $this->fallback->build($project);
            $path = 'fallback';
            $note = 'AI unavailable (' . $e->getMessage() . ') — built a facts-only site instead. No facts were invented.';
        }
        $project->sections()->delete();
        $this->store($project, $sections);
        $project->update(['status' => 'ready']);
        return ['path' => $path, 'note' => $note];
    }

    public function regenerateSection(Project $project, SiteSection $section): array
    {
        $facts = $project->confirmedFacts();
        try {
            $sections = AiClientFactory::make()->generateSections($facts, $section->kind);
            $match = collect($sections)->firstWhere('kind', $section->kind);
            if (! $match) {
                throw new AiUnavailableException('AI did not return the requested section.');
            }
            $this->guard([$match], $facts);
            $section->update(['content' => $match['content'], 'fact_keys' => $match['fact_keys']]);
            return ['path' => 'ai', 'note' => 'Section regenerated by AI.'];
        } catch (AiUnavailableException $e) {
            $built = $this->fallback->build($project, $section->kind);
            if ($built) {
                $section->update(['content' => $built[0]['content'], 'fact_keys' => $built[0]['fact_keys']]);
            }
            return ['path' => 'fallback', 'note' => 'AI unavailable (' . $e->getMessage() . ') — section rebuilt from facts only.'];
        }
    }

    /** Reject AI output that mentions a phone/email not present in the facts. */
    private function guard(array $sections, array $facts): void
    {
        $allowedPhones = [];
        $allowedEmails = [];
        $flat = json_encode($facts);
        if (preg_match_all('/[6-9]\d{4}[\s-]?\d{5}/', $flat, $m)) {
            $allowedPhones = array_map(fn ($p) => preg_replace('/\D/', '', $p), $m[0]);
        }
        if (preg_match_all('/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/', $flat, $m)) {
            $allowedEmails = array_map('strtolower', $m[0]);
        }
        $text = json_encode(array_column($sections, 'content'));
        if (preg_match_all('/[6-9]\d{4}[\s-]?\d{5}/', $text, $m)) {
            foreach ($m[0] as $p) {
                if (! in_array(preg_replace('/\D/', '', $p), $allowedPhones, true)) {
                    throw new AiUnavailableException('AI output mentioned a phone number that is not a confirmed fact.');
                }
            }
        }
        if (preg_match_all('/[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/', $text, $m)) {
            foreach ($m[0] as $e) {
                if (! in_array(strtolower($e), $allowedEmails, true)) {
                    throw new AiUnavailableException('AI output mentioned an email that is not a confirmed fact.');
                }
            }
        }
    }

    private function store(Project $project, array $sections): void
    {
        $order = ['hero', 'about', 'services', 'prices', 'gallery', 'contact', 'footer'];
        usort($sections, fn ($a, $b) => array_search($a['kind'], $order) <=> array_search($b['kind'], $order));
        foreach ($sections as $i => $s) {
            $project->sections()->create([
                'kind' => $s['kind'],
                'position' => $i,
                'content' => $s['content'],
                'fact_keys' => $s['fact_keys'] ?? [],
            ]);
        }
    }
}
